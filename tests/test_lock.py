def test_a_lock_naming_some_other_default_registry_is_not_followed(tmp_path, monkeypatch, reg):
    monkeypatch.delenv("FANBASE_REGISTRY", raising=False)
    monkeypatch.chdir(reg)  # a checkout is found here, so nothing is fetched
    from fanbase.locking import locked_registry

    lock = Lock(registries={"": "https://example.org/somewhere"}, specs=[])
    with pytest.raises(RegistryError, match="pass --registry https://example.org/somewhere"):
        locked_registry(Context(), lock, "")
    assert locked_registry(Context(explicit=str(reg)), lock, "").root == reg  # unless the user says so


def test_a_lock_that_names_the_public_registry_reads_it_from_there(monkeypatch):
    monkeypatch.delenv("FANBASE_REGISTRY", raising=False)
    lock = Lock(registries={"": "https://github.com/fandango-fuzzer/fanbase/tree/v1"})
    ctx = lock_context(lock, None)
    assert ctx._explicit == "https://github.com/fandango-fuzzer/fanbase/tree/v1"  # opened only when needed


@pytest.mark.parametrize("given", ["reg", "env"])
def test_what_the_user_chose_comes_before_the_lock(monkeypatch, reg, given):
    lock = Lock(registries={"": "https://github.com/fandango-fuzzer/fanbase/tree/v1"})
    if given == "env":
        monkeypatch.setenv("FANBASE_REGISTRY", str(reg))
        ctx = lock_context(lock, None)
        assert ctx._explicit is None
    else:
        ctx = lock_context(lock, Registry(reg))
        assert ctx.default.root == reg


# --- fandango -F, which is ensure()

def lock_for(capsys, reg, project, *refs):
    assert run(capsys, "--registry", str(reg), "lock", *refs)[0] == 0


def test_ensure_holds_a_run_to_the_lock(capsys, reg, project, root):
    lock_for(capsys, reg, project, "png-apng")
    assert ensure("png-apng", Registry(reg), root).status == "installed"  # ./fanbase.lock is found
    republish(reg, "png-apng", "<start> ::= 'moved on'\n", version="1.1")
    with pytest.raises(RegistryError, match="png/png-apng was locked at 1.0.*now has 1.1.*fanbase lock"):
        ensure("png-apng", Registry(reg), root)
    assert spec_path(root, "png", "png-apng").read_text() == "<start> ::= 'png-apng'\n"  # still the locked one


def test_ensure_checks_what_a_spec_extends_against_the_lock_too(capsys, reg, project, root):
    lock_for(capsys, reg, project, "png-apng")
    republish(reg, "png", "<start> ::= 'png moved on'\n", version="1.1")
    with pytest.raises(RegistryError, match="png/png was locked"):
        ensure("png-apng", Registry(reg), root)
    assert all_installed(root) == []  # nothing was installed on the way


def test_ensure_without_a_lock_takes_what_the_registry_has(capsys, reg, project, root):
    ensure("png", Registry(reg), root)
    republish(reg, "png", "<start> ::= 'png 2'\n", version="1.1")
    assert ensure("png", Registry(reg), root).status == "updated"


def test_ensure_notes_a_spec_the_lock_does_not_have(capsys, reg, project, root, caplog):
    lock_for(capsys, reg, project, "png")
    with caplog.at_level(logging.WARNING, logger="fanbase"):
        done = ensure("gif", Registry(reg), root)
    assert done.status == "installed" and "gif/gif is not in the lock" in caplog.text


def test_ensure_takes_the_lock_named_in_the_environment(capsys, reg, project, root, monkeypatch, tmp_path):
    lock_for(capsys, reg, project, "png")
    (project / "fanbase.lock").rename(tmp_path / "elsewhere.lock")
    republish(reg, "png", "<start> ::= 'png 2'\n", version="1.1")
    assert ensure("png", Registry(reg), root).status == "installed"  # no lock here: anything goes
    monkeypatch.setenv("FANBASE_LOCK", str(tmp_path / "elsewhere.lock"))
    with pytest.raises(RegistryError, match="was locked"):
        ensure("png", Registry(reg), root, )


def test_ensure_offline_uses_the_installed_copy_only_if_it_is_the_locked_one(capsys, reg, project, root, monkeypatch):
    lock_for(capsys, reg, project, "png")
    ensure("png", Registry(reg), root)
    monkeypatch.setenv("FANBASE_REGISTRY", "http://127.0.0.1:9")
    assert ensure("png", root=root).status == "offline"
    spec_path(root, "png", "png").write_text("# edited\n")
    meta = spec_path(root, "png", "png").with_suffix(".yml")
    data = yaml.safe_load(meta.read_text())
    data["sha256"] = "00" * 32  # the installed copy is not what was locked
    meta.write_text(yaml.safe_dump(data))
    with pytest.raises(RegistryError, match="not the one fanbase.lock says"):
        ensure("png", root=root)
