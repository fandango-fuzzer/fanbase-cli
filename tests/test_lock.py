# --- the file

def test_a_lock_survives_being_written_and_read():
    lock = Lock(
        registries={"": "https://github.com/fandango-fuzzer/fanbase/tree/v1", "acme": "https://example.org/acme"},
        specs=[
            LockedSpec("", "png", "png", "1.0", SHA, True),
            LockedSpec("acme", "png", "png-strict", None, SHA, False),
        ],
    )
    back = load_lock_from_text(dump_lock(lock))
    assert back.registries == lock.registries and back.specs == lock.specs


def load_lock_from_text(text, tmp=[]):
    import pathlib
    import tempfile

    path = pathlib.Path(tempfile.mkdtemp()) / "fanbase.lock"
    path.write_text(text)
    return load_lock(path)


def test_the_file_says_what_it_is_and_names_the_default_registry_fanbase():
    text = dump_lock(Lock(registries={"": "u"}, specs=[LockedSpec("", "png", "png", "1.0", SHA, True)]))
    assert text.startswith("# generated by `fanbase lock`")
    data = yaml.safe_load(text)
    assert data["schema"] == 1 and data["registries"] == {"fanbase": "u"}
    assert data["specs"] == [{"spec": "png/png", "registry": "fanbase", "version": "1.0", "sha256": SHA, "requested": True}]


@pytest.mark.parametrize("change, complaint", [
    ({"schema": 2}, "upgrade fanbase"),
    ({"schema": "x"}, "upgrade fanbase"),
    ({"registries": ["u"]}, "registries has to map"),
    ({"specs": [5]}, "is not a spec"),
    ({"specs": [{"spec": "png", "sha256": SHA}]}, "format/kind"),
    ({"specs": [{"spec": "../x/y", "sha256": SHA}]}, "format/kind"),
    ({"specs": [{"spec": "png/png", "sha256": "nothex"}]}, "64 hex digits"),
    ({"specs": [{"spec": "png/png", "sha256": SHA, "registry": "acme"}]}, "not one of the registries listed"),
    ({"specs": [{"spec": "png/png", "sha256": SHA, "version": 1.0}]}, "version has to be text"),
])
def test_a_lock_that_is_not_valid_is_refused(change, complaint, tmp_path):
    data = {"schema": 1, "registries": {"fanbase": "u"}, "specs": []} | change
    path = tmp_path / "bad.lock"
    path.write_text(yaml.safe_dump(data))
    with pytest.raises(RegistryError, match=complaint):
        load_lock(path)


def test_a_missing_lock_says_how_to_make_one(tmp_path):
    with pytest.raises(RegistryError, match="fanbase lock SPEC"):
        load_lock(tmp_path / "nope.lock")


# --- fanbase lock

def test_lock_records_the_specs_and_what_they_extend(capsys, reg, project):
    code, out, _ = run(capsys, "--registry", str(reg), "lock", "png-apng")
    assert code == 0 and "locked 2 specs in fanbase.lock" in out
    lock = load_lock(project / "fanbase.lock")
    assert [(str(s), s.version, s.requested) for s in lock.specs] == [("png/png", "1.0", False), ("png/png-apng", "1.0", True)]
    index = yaml.safe_load((reg / INDEX_FILENAME).read_text())
    shas = {row["kind"]: row["sha256"] for row in index["specs"]}
    assert all(s.sha256 == shas[s.kind] for s in lock.specs)
    assert lock.registries == {"": str(reg)}


def test_lock_with_no_names_refreshes_what_was_asked_for(capsys, reg, project):
    run(capsys, "--registry", str(reg), "lock", "png-apng")
    republish(reg, "png", "<start> ::= 'png 2'\n", version="1.1")
    code, out, _ = run(capsys, "--registry", str(reg), "lock")
    assert code == 0 and "changed  png/png: 1.0" in out and "-> 1.1" in out
    assert load_lock(project / "fanbase.lock").find("", "png", "png").version == "1.1"
    assert [str(s) for s in load_lock(project / "fanbase.lock").requested] == ["png/png-apng"]


