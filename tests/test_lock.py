def run(capsys, *argv):
    code = main(list(argv))
    out = capsys.readouterr()
    return code, out.out, out.err


def build(root, specs, name=None):
    for (fmt, kind), meta in specs.items():
        write_spec(root, fmt, kind, f"<start> ::= '{kind}'\n", meta.pop("description", kind), **meta)
    if name:
        (root / "registry.yml").write_text(yaml.safe_dump({"name": name}))
    reg = Registry(root)
    rows, _, _ = reindex(reg)
    (root / INDEX_FILENAME).write_text(dump_index(rows, reg.info))
    return root


def republish(root, kind, text, **meta):
    """The registry changes a spec: new text, and optionally new metadata."""
    fmt = kind.split("-")[0]
    (root / "specs" / fmt / kind / f"{kind}.fan").write_text(text)
    if meta:
        path = root / "specs" / fmt / kind / "metadata.yml"
        data = yaml.safe_load(path.read_text())
        data.update(meta)
        path.write_text(yaml.safe_dump(data))
    reg = Registry(root)
    rows, _, _ = reindex(reg)
    (root / INDEX_FILENAME).write_text(dump_index(rows, reg.info))


