    path.write_text(path.read_text().replace(str(acme.resolve()), "https://elsewhere.example/acme"))
    code, _, err = run(capsys, "--registry", str(reg), "install", "--locked")
    assert code == 0 and "you added acme as" in err and "elsewhere.example" in err  # the hashes still hold


