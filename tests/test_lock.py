def test_locked_installs_exactly_what_the_lock_says(capsys, reg, project, root):
    run(capsys, "--registry", str(reg), "lock", "png-apng")
    code, out, _ = run(capsys, "--registry", str(reg), "install", "--locked")
    assert code == 0 and "2 specs from fanbase.lock: 2 installed" in out
    assert [str(d) for d in all_installed(root)] == ["png/png", "png/png-apng"]


def test_locked_installs_nothing_if_a_registry_has_moved_on(capsys, reg, project, root):
    run(capsys, "--registry", str(reg), "lock", "png-apng")
    republish(reg, "png", "<start> ::= 'png 2'\n", version="1.1")
