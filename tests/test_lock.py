@pytest.fixture
def acme(tmp_path):
    return build(tmp_path / "acme", {("png", "png-strict"): dict(version="1.0")}, name="acme")


def test_a_lock_with_a_registry_you_added(capsys, reg, acme, project, root):
    run(capsys, "--registry", str(reg), "registry", "add", str(acme), "--trust")
    run(capsys, "--registry", str(reg), "lock", "png", "acme:png-strict")
    lock = load_lock(project / "fanbase.lock")
    assert lock.registries["acme"] == str(acme.resolve()) and lock.find("acme", "png", "png-strict").requested
    code, out, _ = run(capsys, "--registry", str(reg), "install", "--locked")
    assert code == 0 and "2 specs" in out
    assert spec_path(root, "png", "png-strict", "acme").is_file()


def test_a_lock_that_uses_a_registry_you_have_not_added(capsys, reg, acme, project, root):
    run(capsys, "--registry", str(reg), "registry", "add", str(acme), "--trust")
    run(capsys, "--registry", str(reg), "lock", "acme:png-strict")
    run(capsys, "--registry", str(reg), "registry", "remove", "acme")
    code, _, err = run(capsys, "--registry", str(reg), "install", "--locked")
    assert code == 2 and "which you have not added" in err and "registry add" in err and "--name acme" in err
    assert all_installed(root) == []


def test_a_registry_you_added_elsewhere_than_the_lock_says_is_pointed_out(capsys, reg, acme, project, tmp_path):
    run(capsys, "--registry", str(reg), "registry", "add", str(acme), "--trust")
